# 导入必要的库
import pandas as pd
from sklearn.linear_model import LinearRegression
import numpy as np

# 1. 构建数据集（对应表格中的功率、重量、价格）
# 特征：功率(x1)、重量(x2)；目标值：价格(y)
data = {
    '功率(千瓦)': [111, 68, 76, 76, 76, 76, 86, 100, 68, 101, 101, 68, 69, 97],
    '重量(千克)': [2548, 1876, 1819, 1940, 1956, 2010, 2236, 2293, 1890, 2380, 2380, 1918, 1889, 2302],
    '价格(元)': [165000, 55720, 68550, 65290, 71290, 72950, 78950, 103450, 51950, 109450, 118450, 53890, 54990, 95490]
}

# 转换为DataFrame（方便数据处理）
df = pd.DataFrame(data)

# 2. 准备特征矩阵X和目标向量y
# X：特征（功率、重量），y：价格
X = df[['功率(千瓦)', '重量(千克)']]
y = df['价格(元)']

# 3. 训练线性回归模型
model = LinearRegression()
model.fit(X, y)

# 4. 提取系数和截距
k1 = model.coef_[0]  # 功率的斜率k1
k2 = model.coef_[1]  # 重量的斜率k2
b = model.intercept_ # 截距b

# 5. 输出结果（保留2位小数，更易读）
print("===== 多元线性回归系数结果 =====")
print(f"功率的斜率 k1 = {k1:.2f}")
print(f"重量的斜率 k2 = {k2:.2f}")
print(f"截距 b = {b:.2f}")

# 6. 输出回归方程
print("\n===== 回归方程 =====")
print(f"价格(y) = {k1:.2f} * 功率(x1) + {k2:.2f} * 重量(x2) + {b:.2f}")

# 可选：输出模型拟合优度R²（越接近1拟合效果越好）
r2 = model.score(X, y)
print(f"\n模型拟合优度 R² = {r2:.4f}")